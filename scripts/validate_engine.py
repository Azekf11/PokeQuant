"""Generate research/reports/validation.md and its figure (protocol §4.4, roadmap S5).

Checks the Monte Carlo engine against closed-form results. No price is used:
values are synthetic (1 for every printing, or a fixed pseudo-random vector).
The real-set checks use the posterior-mean booster model of Surging Sparks,
built from the processed tables (run `pokequant ingest ... --offline` first).

Usage: uv run python scripts/validate_engine.py
"""

from __future__ import annotations

import math
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy import stats

from pokequant_core import __version__
from pokequant_core.booster import LAYOUTS, build_set_posterior
from pokequant_core.ingest.store import read_records
from pokequant_core.model import BoosterModel, Slot, p_card_in_slot, p_hit
from pokequant_core.runner import generators
from pokequant_core.schemas import CardPrinting, PullRateObservation
from pokequant_core.simulate import (
    compile_model,
    open_packs,
    pack_values,
    simulate_e1,
    simulate_e2,
    values_vector,
)

ROOT = Path(__file__).resolve().parents[1]
PROCESSED = ROOT / "data/processed/pokelife-2026-11-13_tcgdex-2026-11-15"
REPORT = ROOT / "research/reports/validation.md"
FIGURE = ROOT / "research/reports/figures/mc_error_decay.png"
SEED = 20261115


def toy() -> BoosterModel:
    return BoosterModel(
        product_id="toy",
        set_id="toy",
        version="toy",
        cards_by_rarity={"hit": ["x"], "miss": ["y"]},
        slots=[Slot(slot_id="s", outcomes={"hit": 0.3, "miss": 0.7})],
    )


def main() -> None:
    rng_toy, rng_freq, rng_bin, rng_err, rng_path, rng_cu, rng_e2 = generators(SEED, 7)
    lines = [
        "# Monte Carlo engine validation",
        "",
        f"Generated by `scripts/validate_engine.py` (pokequant {__version__}, seed {SEED}).",
        "No price is used: card values are synthetic. Real-set checks use the",
        "posterior-mean booster model of Surging Sparks (sv08, layout `tcgplayer`).",
        "",
    ]

    # 1. Toy case
    cm = compile_model(toy())
    v = values_vector(cm, {"x": 10.0, "y": 0.0})
    x = pack_values(cm, v, rng_toy, 1_000_000)
    lines += [
        "## 1. Toy case: one slot, two cards",
        "",
        "Card x (value 10) with probability 0.3, card y (value 0) otherwise;",
        "exact mean 3, exact variance 21. N = 10⁶ packs.",
        "",
        "| | Exact | Simulated | Deviation / SE |",
        "|---|---|---|---|",
        f"| Mean | 3 | {x.mean():.4f} | {abs(x.mean() - 3) / math.sqrt(21 / len(x)):.2f} |",
        f"| Variance | 21 | {x.var():.4f} | — |",
        "",
    ]

    # Real-set model
    printings = read_records(PROCESSED / "printings.parquet", CardPrinting)
    rates = read_records(PROCESSED / "pull_rates.parquet", PullRateObservation)
    model = build_set_posterior("sv08", printings, rates, LAYOUTS["tcgplayer"]).mean_model()
    cm = compile_model(model, distinct_groups=())

    # 2. Card frequencies per slot
    n = 1_000_000
    cards = open_packs(cm, rng_freq, n)
    lines += [
        "## 2. Simulated card frequencies vs theory (sv08)",
        "",
        f"χ² goodness of fit of the printing drawn in each random slot, N = {n:,} packs.",
        "",
        "| Slot | Printings with p > 0 | χ² | d.f. | p-value |",
        "|---|---|---|---|---|",
    ]
    for col, slot in enumerate(model.slots):
        if slot.slot_id not in {"rev1", "rev2", "rare"}:
            continue
        observed = np.bincount(cards[:, col], minlength=len(cm.printing_ids))
        expected = np.array([p_card_in_slot(model, slot, p) for p in cm.printing_ids]) * n
        keep = expected > 0
        test = stats.chisquare(observed[keep], expected[keep])
        lines.append(
            f"| {slot.slot_id} | {keep.sum()} | {test.statistic:.1f} | {keep.sum() - 1} "
            f"| {test.pvalue:.3f} |"
        )
    lines.append("")

    # 3. Hit counts vs binomial
    target = model.cards_by_rarity["special illustration rare"][0]
    p = p_hit(model, target)
    packs, runs = 100, 50_000
    hits = open_packs(cm, rng_bin, packs * runs).reshape(runs, packs, -1) == cm.index(target)
    counts = hits.any(axis=2).sum(axis=1)
    lines += [
        "## 3. Hit counts vs binomial (sv08, one Special Illustration Rare)",
        "",
        f"Packs containing the target among {packs} packs, {runs:,} runs;",
        f"p_hit = {p:.6f}.",
        "",
        "| | Binomial | Simulated |",
        "|---|---|---|",
        f"| Mean | {packs * p:.4f} | {counts.mean():.4f} |",
        f"| Variance | {packs * p * (1 - p):.4f} | {counts.var():.4f} |",
        f"| P(at least one) | {1 - (1 - p) ** packs:.4f} | {np.mean(counts > 0):.4f} |",
        "",
    ]

    # 4. Error decay
    cm_toy = compile_model(toy())
    v_toy = values_vector(cm_toy, {"x": 10.0, "y": 0.0})
    sizes = [10**k for k in range(3, 7)]
    reps = 50

    def rmse_at(size: int) -> float:
        errors = [(pack_values(cm_toy, v_toy, rng_err, size).mean() - 3) ** 2 for _ in range(reps)]
        return math.sqrt(float(np.mean(errors)))

    rmse = [rmse_at(s) for s in sizes]
    slope = float(np.polyfit(np.log10(sizes), np.log10(rmse), 1)[0])
    FIGURE.parent.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(5, 3.5))
    ax.loglog(sizes, rmse, "o-", label="simulated RMSE of the mean")
    ax.loglog(sizes, [math.sqrt(21 / s) for s in sizes], "--", label="theory √(σ²/N)")
    ax.set_xlabel("N (packs)")
    ax.set_ylabel("RMSE")
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(FIGURE, dpi=150, metadata={"Software": None})
    plt.close(fig)
    lines += [
        "## 4. Monte Carlo error decay",
        "",
        f"RMSE of the toy-case mean over {reps} repetitions per N;",
        f"fitted log-log slope = {slope:.3f} (theory: -0.5).",
        "",
        "| N | RMSE | Theory √(21/N) |",
        "|---|---|---|",
        *[
            f"| {s:,} | {e:.5f} | {math.sqrt(21 / s):.5f} |"
            for s, e in zip(sizes, rmse, strict=True)
        ],
        "",
        "![Error decay](figures/mc_error_decay.png)",
        "",
    ]

    # 5. Aggregate path and A-CU
    values = np.random.default_rng(1).gamma(0.5, 4.0, len(cm.printing_ids))
    exact = simulate_e1(cm, values, rng_path, n_packs=10, booster_cost=0.0, runs=100_000,
                        exact_packs=True)  # fmt: skip
    fast = simulate_e1(cm, values, rng_path, n_packs=10, booster_cost=0.0, runs=100_000)
    cm_cu = compile_model(model)
    with_cu = simulate_e1(cm_cu, values, rng_cu, n_packs=10, booster_cost=0.0, runs=100_000,
                          exact_packs=True)  # fmt: skip
    ks = stats.ks_2samp(exact, fast)
    lines += [
        "## 5. Aggregate (multinomial) path and assumption A-CU",
        "",
        "Total synthetic value of 10 packs, 100,000 runs each.",
        "",
        "| Path | Mean | Std | 5 % quantile |",
        "|---|---|---|---|",
        *[
            f"| {name} | {a.mean():.3f} | {a.std():.3f} | {np.quantile(a, 0.05):.3f} |"
            for name, a in (
                ("Card by card, with replacement", exact),
                ("Aggregate (multinomial)", fast),
                ("Card by card, A-CU (distinct C/U)", with_cu),
            )
        ],
        "",
        f"Kolmogorov-Smirnov, card by card vs aggregate: p = {ks.pvalue:.3f}.",
        "A-CU changes the standard deviation by "
        f"{(with_cu.std() / exact.std() - 1) * 100:+.2f} %, which justifies the aggregate path.",
        "",
    ]

    # 6. E2 and reproducibility
    nmax = math.ceil(3 / p)
    ones = np.ones(len(cm.printing_ids))
    _, opened = simulate_e2(cm, ones, rng_e2, target=target, booster_cost=1.0,
                            target_price=0.0, n_max=nmax, runs=100_000)  # fmt: skip
    a = simulate_e1(cm, values, generators(1, 1)[0], n_packs=3, booster_cost=0.0, runs=1000)
    b = simulate_e1(cm, values, generators(1, 1)[0], n_packs=3, booster_cost=0.0, runs=1000)
    lines += [
        "## 6. Packs to the target (E2) and reproducibility",
        "",
        f"Cap n_max = ⌈3 / p_hit⌉ = {nmax}; 100,000 runs.",
        "",
        "| | Theory | Simulated |",
        "|---|---|---|",
        f"| E[min(K, n_max)] | {(1 - (1 - p) ** nmax) / p:.1f} | {opened.mean():.1f} |",
        f"| P(no hit by n_max) | {(1 - p) ** nmax:.4f} | {np.mean(opened == nmax):.4f} |",
        "",
        f"Same seed, data and model ⇒ identical output: {bool(np.array_equal(a, b))}.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)} and {FIGURE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
