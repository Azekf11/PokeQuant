"""Report of the ten-set extension (ADR 0015, tag prereg-v4).

Reads a run of research/experiments/extension_sets.yaml and writes
research/reports/extension_sets.md and the paper figure fig8_ten_sets.png:
C1-C3 by set, break-even prices, and H1-H4 over the ten sets, with and
without the sets flagged by the duplicate rule F1.

Usage: uv run python scripts/extension_report.py results/<extension run>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from pokequant_core.analysis import hypotheses
from pokequant_core.experiment import load_experiment
from pokequant_core.experiment_run import processed_dir
from pokequant_core.ingest.store import read_records
from pokequant_core.metrics import epistemic_interval
from pokequant_core.robustness import check_conclusions
from pokequant_core.schemas import CardSet

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research/reports/extension_sets.md"
FIGURE = ROOT / "research/paper/figures/fig8_ten_sets.png"
FLAGGED = ("sv02", "sv04")  # F1, research/reports/pull_rate_checks.md
MAIN_SETS = ("sv07", "sv08", "sv10")
INK2, MUTED, GRID = "#52514e", "#898781", "#e1e0d9"
COLORS = {"central": "#2a78d6", "gross": "#eb6834"}


def yes(flag: bool) -> str:
    return "yes" if flag else "**no**"


def figure(rows: list[dict[str, Any]], cost: float) -> None:
    fig, ax = plt.subplots(figsize=(7.2, 3.4))
    for k, r in enumerate(rows):
        for scenario, dy in (("central", -0.12), ("gross", 0.12)):
            mean, low, high = r["b"][scenario]
            ax.plot([low, high], [k + dy, k + dy], color=COLORS[scenario], lw=2.2)
            ax.plot(mean, k + dy, "o", color=COLORS[scenario], ms=4.5, mec="white", mew=0.8)
    ax.axvline(cost, color=INK2, lw=0.9, ls="--")
    ax.set_yticks(
        range(len(rows)),
        [f"{r['name']} ({r['set_id']}){' *' if r['set_id'] in FLAGGED else ''}" for r in rows],
    )
    ax.invert_yaxis()
    ax.grid(axis="y", visible=False)
    ax.grid(axis="x", color=GRID, lw=0.6)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    ax.set_xlabel("Break-even booster price b*, USD")
    ax.plot([], [], color=COLORS["central"], lw=2.2, label="Central costs")
    ax.plot([], [], color=COLORS["gross"], lw=2.2, label="Gross (no frictions)")
    ax.legend(fontsize=7, loc="lower right", bbox_to_anchor=(1.0, 1.0), ncol=2, frameon=False)
    fig.text(
        0.0,
        -0.04,
        "Posterior mean and 95 % interval over 200 pull-rate draws. Dashed: retail price "
        f"{cost:.2f} USD. * flagged by the duplicate rule F1.\n"
        "Prices: TCGplayer market price (provider aggregate), USD, 2026-11-15.",
        fontsize=7,
        color=MUTED,
        va="top",
    )
    FIGURE.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIGURE, dpi=200, bbox_inches="tight", metadata={"Software": None})
    plt.close(fig)


def main(run_dir: Path) -> None:
    manifest = json.loads((run_dir / "manifest.json").read_text(encoding="utf-8"))
    cfg = load_experiment(ROOT / manifest["run"]["parameters"]["config"])
    results: list[dict[str, Any]] = json.loads(
        (run_dir / "results.json").read_text(encoding="utf-8")
    )
    cost = cfg.scenario("central").booster_cost
    names = {
        s.set_id: s.name for s in read_records(processed_dir(ROOT, cfg) / "sets.parquet", CardSet)
    }
    rows: list[dict[str, Any]] = []
    for set_id in cfg.sets:
        own = [r for r in results if r["set_id"] == set_id]
        checks = check_conclusions(own, cost)
        e1 = next(r for r in own if r["job"]["label"] == "n=36")
        mean36 = np.asarray(e1["a_metrics"]["central"]["mean"])
        b: dict[str, tuple[float, float, float]] = {}
        for scenario in ("central", "gross"):
            x = np.asarray(e1["extra"]["break_even_booster_price"][scenario])
            low, high = epistemic_interval(x)
            b[scenario] = (float(x.mean()), low, high)
        rows.append(
            {
                "set_id": set_id,
                "name": names[set_id],
                "b": b,
                "mean36": (float(mean36.mean()), *epistemic_interval(mean36)),
                "b36": float(e1["b_metrics"]["central"]["mean"]),
                "checks": checks,
            }
        )
    figure(rows, cost)

    def fmt(t: tuple[float, float, float]) -> str:
        return f"{t[0]:.2f} [{t[1]:.2f}, {t[2]:.2f}]"

    all_h = hypotheses(results)
    kept = [r for r in results if r["set_id"] not in FLAGGED]
    kept_h = hypotheses(kept)
    added = [r for r in rows if r["set_id"] not in MAIN_SETS]
    lines = [
        "# Extension to the ten evaluable sets (ADR 0015, tag `prereg-v4`)",
        "",
        f"Generated by `scripts/extension_report.py` from run `{run_dir.name}`",
        f"(configuration `{manifest['run']['parameters']['config']}`, results SHA-256",
        f"`{manifest['results_sha256'][:16]}…`). Same seed, prior, draws, runs, scenarios",
        "and price snapshot as the main run; TCGplayer market prices of 2026-11-15.",
        "",
        "## Conclusions by set (central scenario; C2 also checks the gross b*)",
        "",
        "| Set | Central b* | Gross b* | A: mean Π, 36 boosters | B: Π, 36 boosters "
        "| C1 | C2 | C3 | Flag F1 |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        c = r["checks"]
        lines.append(
            f"| {r['name']} ({r['set_id']}) | {fmt(r['b']['central'])} | {fmt(r['b']['gross'])} "
            f"| {fmt(r['mean36'])} | {r['b36']:.2f} | {yes(c['C1']['holds'])} "
            f"| {yes(c['C2']['holds'])} | {yes(c['C3']['holds'])} "
            f"| {'flagged' if r['set_id'] in FLAGGED else ''} |"
        )
    fails = [
        f"- {r['set_id']} {ck}: " + "; ".join(r["checks"][ck]["fails"])
        for r in rows
        for ck in ("C1", "C2", "C3")
        if not r["checks"][ck]["holds"]
    ]
    central = [r["b"]["central"][0] for r in added]
    gross = [r["b"]["gross"][0] for r in added]
    lines += [
        "",
        "Failures:" if fails else "Failures: none. C1, C2 and C3 hold in every set.",
        *fails,
        "",
        f"Seven added sets: central b* {min(central):.2f} to {max(central):.2f}, "
        f"gross b* {min(gross):.2f} to {max(gross):.2f} (posterior means).",
        "",
        "## Hypotheses over the ten sets",
        "",
        "| Hypothesis | Ten sets | Without flagged sets (sv02, sv04) |",
        "|---|---|---|",
        *(
            f"| {h} | {all_h[h]['status']} | {kept_h[h]['status']} |"
            for h in ("H1", "H2", "H3", "H4")
        ),
        "",
        "### H4 evidence (decisive winner on the mean, central scenario)",
        "",
        *(f"- {line}" for line in all_h["H4"]["evidence"]),
        "",
        "### H1 and H2 evidence (ten sets)",
        "",
        *(f"- H1: {line}" for line in all_h["H1"]["evidence"]),
        *(f"- H2: {line}" for line in all_h["H2"]["evidence"]),
        "",
        "H4 here covers sets only. The date half of H4 uses the weekly panel of ADR 0014.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} and {FIGURE}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
