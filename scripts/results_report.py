"""Generate research/reports/results.md from one run of the main experiment.

Reads results/<run_id>/ written by `pokequant run research/experiments/main.yaml`
and recomputes every comparison and verdict from results.json (ADR 0011). No
per-card price is published (ADR 0009): E2 targets are named by rarity only.

Usage: uv run python scripts/results_report.py results/<run_id>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import numpy as np

from pokequant_core.analysis import comparison_rows, hypotheses
from pokequant_core.experiment import load_experiment
from pokequant_core.experiment_run import processed_dir
from pokequant_core.ingest.store import read_records
from pokequant_core.metrics import epistemic_interval
from pokequant_core.schemas import CardPrinting

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "research/reports/results.md"
SHORT = {"decisive: A": "**A**", "decisive: B": "**B**", "undetermined": "undet.", "tie": "tie"}


def interval(values: list[float], fmt: str = "{:.2f}") -> str:
    low, high = epistemic_interval(np.asarray(values))
    return f"{fmt.format(float(np.mean(values)))} [{fmt.format(low)}, {fmt.format(high)}]"


def e1_table(results: list[dict[str, Any]], scenario: str, cost: dict[str, float]) -> list[str]:
    lines = [
        "| Set | Packs | Budget | A: mean Π | A: median Π | A: P(loss) | A: CVaR 5 % "
        "| B: Π | Verdict mean / median / CVaR |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for res in results:
        if res["job"]["estimand"] != "E1":
            continue
        n = res["job"]["n_packs"]
        a, b = res["a_metrics"][scenario], res["b_metrics"][scenario]
        rows = {
            r["metric"]: r for r in comparison_rows(res) if r["scenario"] == scenario
        }  # fmt: skip
        budget = n * cost[scenario]
        lines.append(
            f"| {res['set_id']} | {n} | {budget:.2f} | {interval(a['mean'])} "
            f"| {interval(a['median'])} | {interval(a['p_loss'], '{:.3f}')} "
            f"| {interval(a['cvar05'])} | {b['mean']:.2f} "
            f"| {SHORT[rows['mean']['verdict']]} / {SHORT[rows['median']['verdict']]} "
            f"/ {SHORT[rows['cvar05']['verdict']]} |"
        )
    return lines


def e2_table(results: list[dict[str, Any]], scenario: str, rarity: dict[str, str]) -> list[str]:
    lines = [
        "| Set | Target | p_hit (1 in …) | n_max | P(K < a(c*)) | A: mean Π | A: median Π "
        "| A: CVaR 5 % | Verdict mean / median / CVaR |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for res in results:
        if res["job"]["estimand"] != "E2":
            continue
        a = res["a_metrics"][scenario]
        rows = {r["metric"]: r for r in comparison_rows(res) if r["scenario"] == scenario}
        inv = 1 / np.asarray(res["extra"]["p_hit"])
        lo, hi = epistemic_interval(inv)
        lines.append(
            f"| {res['set_id']} | {res['job']['label']} ({rarity[res['extra']['target']]}) "
            f"| {inv.mean():.0f} [{lo:.0f}, {hi:.0f}] | {res['extra']['n_max']} "
            f"| {interval(a['p_gain'], '{:.3f}')} | {interval(a['mean'])} "
            f"| {interval(a['median'])} | {interval(a['cvar05'])} "
            f"| {SHORT[rows['mean']['verdict']]} / {SHORT[rows['median']['verdict']]} "
            f"/ {SHORT[rows['cvar05']['verdict']]} |"
        )
    return lines


def main(run_dir: Path) -> None:
    results = json.loads((run_dir / "results.json").read_text())
    manifest = json.loads((run_dir / "manifest.json").read_text())
    run = manifest["run"]
    params = run["parameters"]
    scenarios = params["scenarios"]
    verdicts = hypotheses(results)
    cfg = load_experiment(ROOT / params["config"])
    cost = {s.name: s.booster_cost for s in cfg.cost_scenarios}
    printings = read_records(processed_dir(ROOT, cfg) / "printings.parquet", CardPrinting)
    rarity = {p.printing_id: p.rarity for p in printings}
    lines = [
        "# Results of the main experiment",
        "",
        f"Generated by `scripts/results_report.py` from run `{run['run_id']}`",
        f"(seed {run['seed']}, {params['epistemic_draws']} epistemic draws x",
        f"{params['aleatory_runs']:,} simulated runs per draw; results.json sha256",
        f"`{manifest['results_sha256'][:12]}…`). Config: `{params['config']}` (tag",
        "`prereg-v2`); decision rules: ADR 0011. Regenerate with:",
        "",
        "```bash",
        f"uv run pokequant run {params['config']}",
        f"uv run python scripts/results_report.py results/{run['run_id']}",
        "```",
        "",
        "Π is a net profit in USD; Strategy A opens boosters and sells every card,",
        "Strategy B buys cards directly. Each cell gives the posterior mean of the",
        "metric over epistemic draws and its 95 % interval. A verdict is **A** or",
        "**B** when that strategy is better in at least 90 % of the draws, `undet.`",
        "otherwise. CVaR 5 % is a positive loss (lower is better). Prices are",
        "TCGplayer market prices (a provider aggregate, not realised sales) at",
        "2026-11-15; fees, shipping and haircuts follow the cost scenarios of §5.2",
        "of the paper. Every number is conditional on these assumptions.",
        "",
        "## 1. Break-even booster price",
        "",
        "Expected liquidation value of one booster, b* = E[Σ l(C_i)] (USD): opening",
        "has a positive expected net profit only if a booster costs less than b*.",
        "",
        "| Set | " + " | ".join(scenarios) + " |",
        "|---|" + "---|" * len(scenarios),
    ]
    for res in results:
        if res["job"]["label"] == "n=1":
            be = res["extra"]["break_even_booster_price"]
            lines.append(
                f"| {res['set_id']} | " + " | ".join(interval(be[s]) for s in scenarios) + " |"
            )
    for scenario in ("central", "adverse", "gross"):
        title = {"central": "main result", "adverse": "prudent", "gross": "reference only"}
        lines += [
            "",
            f"## 2.{('central', 'adverse', 'gross').index(scenario) + 1} E1: budget, "
            f"{scenario} scenario ({title[scenario]})",
            "",
            *e1_table(results, scenario, cost),
        ]
    for scenario in ("central", "adverse", "gross"):
        lines += [
            "",
            f"## 3.{('central', 'adverse', 'gross').index(scenario) + 1} E2: target, "
            f"{scenario} scenario",
            "",
            *e2_table(results, scenario, rarity),
        ]
    lines += [
        "",
        "In E2, Π = a(c*) - K: positive when opening until the target was cheaper",
        "than buying it; Strategy B has Π = 0 exactly. P(K < a(c*)) is the share of",
        "simulated runs in which opening was cheaper. The target's price is not",
        "shown (ADR 0009).",
        "",
        "## 4. Pre-registered hypotheses",
        "",
    ]
    for h, v in verdicts.items():
        lines += [f"**{h}: {v['status']}.**", ""]
        lines += [f"- {e}" for e in v["evidence"]] or ["- no qualifying comparison"]
        lines.append("")
    lines += [
        "H3 lines marked * have a 95 % interval strictly above 0.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
