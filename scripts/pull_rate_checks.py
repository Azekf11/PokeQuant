"""Pull-rate checks of ADR 0015 (tag prereg-v4): source check S1, duplicate flag F1,
held-out predictive check P1.

Usage: uv run python scripts/pull_rate_checks.py
"""

from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path
from typing import Any

from pokequant_core.estimation import beta_posterior, holm, predictive_check

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "data/raw/pokelife/2026-11-13/pull-rates.csv"
PUBLISHED = {
    "main": ROOT / "research/reports/tcgplayer_published_rates.csv",
    "extension": ROOT / "research/reports/extension/tcgplayer_published_rates.csv",
}
OUT_CSV = ROOT / "research/reports/extension/predictive_check.csv"
OUT_MD = ROOT / "research/reports/pull_rate_checks.md"
POKELIFE_SET = {
    "sv01": "scarlet-violet",
    "sv02": "paldea-evolved",
    "sv03": "obsidian-flames",
    "sv04": "paradox-rift",
    "sv05": "temporal-forces",
    "sv06": "twilight-masquerade",
    "sv07": "stellar-crown",
    "sv08": "surging-sparks",
    "sv09": "journey-together",
    "sv10": "destined-rivals",
}
Z = 1.959964
ALPHA = 0.05


def read(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def main() -> None:
    registry = {(r["set_id"], r["rarity"]): r for r in read(REGISTRY)}
    published = {k: read(p) for k, p in PUBLISHED.items()}

    # S1: registry rate vs printed rate, seven added sets.
    s1 = []
    for pub in published["extension"]:
        reg = registry[(POKELIFE_SET[pub["set_id"]], pub["rarity"])]
        pooled = len(reg["datasets"].split()) > 1
        reg_pct = round(float(reg["rate"]) * 100, 2)
        printed = float(pub["rate_pct"])
        status = "pooled" if pooled else ("agrees" if reg_pct == printed else "differs")
        s1.append((pub["set_id"], pub["rarity"], printed, reg_pct, reg["datasets"], status))

    # F1: sets sharing >= 2 identical (rarity, rate, margin) rows in their sources.
    rows: dict[str, set[tuple[str, str, str]]] = {}
    for pub in [*published["main"], *published["extension"]]:
        rows.setdefault(pub["set_id"], set()).add(
            (pub["rarity"], pub["rate_pct"], pub["ci95_halfwidth_pct"])
        )
    shared: dict[tuple[str, str], set[tuple[str, str, str]]] = defaultdict(set)
    ids = sorted(rows)
    for i, a in enumerate(ids):
        for b in ids[i + 1 :]:
            common = rows[a] & rows[b]
            if common:
                shared[a, b] = common
    flagged = sorted({s for pair, c in shared.items() if len(c) >= 2 for s in pair})

    # P1: TCGplayer-only posterior predicts the second dataset of pooled rows.
    p1: list[dict[str, Any]] = []
    for pub in [*published["main"], *published["extension"]]:
        reg = registry[(POKELIFE_SET[pub["set_id"]], pub["rarity"])]
        if len(reg["datasets"].split()) < 2:
            continue
        p, h = float(pub["rate_pct"]) / 100, float(pub["ci95_halfwidth_pct"]) / 100
        n1 = round(p * (1 - p) * (Z / h) ** 2)
        x1 = round(p * n1)
        n2, x2 = int(reg["packs"]) - n1, int(reg["hits"]) - x1
        check = predictive_check(beta_posterior(x1, n1), x2, n2)
        p1.append(
            {
                "set_id": pub["set_id"],
                "rarity": pub["rarity"],
                "datasets": reg["datasets"],
                "tcgplayer_hits": x1,
                "tcgplayer_packs": n1,
                "heldout_hits": x2,
                "heldout_packs": n2,
                "predicted_mean": round(check.expected, 1),
                "pi95_low": check.low,
                "pi95_high": check.high,
                "inside_pi95": check.inside,
                "p_value": round(check.p_value, 4),
            }
        )
    rejected = holm([r["p_value"] for r in p1], ALPHA)
    for r, rej in zip(p1, rejected, strict=True):
        r["holm_reject_at_0.05"] = rej
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    with OUT_CSV.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(p1[0]))
        writer.writeheader()
        writer.writerows(p1)

    agree = sum(r[5] == "agrees" for r in s1)
    tested = sum(r[5] != "pooled" for r in s1)
    inside = sum(r["inside_pi95"] for r in p1)
    lines = [
        "# Pull-rate checks (ADR 0015, tag `prereg-v4`)",
        "",
        "Generated by `scripts/pull_rate_checks.py` from the Poké Life registry snapshot",
        "2026-11-13 and the TCGplayer articles read on 2026-11-15",
        "([main sets](tcgplayer_published_rates.csv),",
        "[added sets](extension/tcgplayer_published_rates.csv)).",
        "",
        "## S1. Registry against the primary source (seven added sets)",
        "",
        f"{agree} of {tested} single-source rows agree with the printed rate to two decimals;",
        f"{len(s1) - tested} rows pool a second dataset and are not tested.",
        "",
        "| Set | Rarity | Printed (%) | Registry (%) | Datasets | Status |",
        "|---|---|---|---|---|---|",
        *(f"| {a} | {b} | {c:.2f} | {d:.2f} | {e} | {f} |" for a, b, c, d, e, f in s1),
        "",
        "## F1. Identical rows across sets in the primary source",
        "",
        "| Sets | Shared rows (rarity, rate %, margin %) |",
        "|---|---|",
        *(
            f"| {a}, {b} | " + "; ".join(f"{r} {x} ± {m}" for r, x, m in sorted(c)) + " |"
            for (a, b), c in sorted(shared.items())
        ),
        "",
        f"Flagged sets (two or more shared rows): {', '.join(flagged) or 'none'}.",
        "A single shared row is plausible at two-decimal precision and is not flagged.",
        "",
        "## P1. Held-out predictive check",
        "",
        "The TCGplayer counts alone (reconstructed from the printed rate and margin,",
        "Jeffreys prior) predict the hits of the second dataset in its own packs",
        "(beta-binomial posterior predictive). Two-sided mid-p values, Holm",
        f"correction at family-wise level {ALPHA}.",
        "",
        f"- Rows: {len(p1)}; observed hits inside the 95 % predictive interval: "
        f"{inside} of {len(p1)} ({inside / len(p1):.0%}).",
        f"- Rows rejected after Holm: {sum(rejected)}.",
        f"- Smallest p-value: {min(r['p_value'] for r in p1):.3f}.",
        "",
        "| Set | Rarity | TCGplayer x/n | Held-out x/n | Predicted mean | 95 % PI | p |",
        "|---|---|---|---|---|---|---|",
        *(
            f"| {r['set_id']} | {r['rarity']} | {r['tcgplayer_hits']}/{r['tcgplayer_packs']} "
            f"| {r['heldout_hits']}/{r['heldout_packs']} | {r['predicted_mean']} "
            f"| [{r['pi95_low']}, {r['pi95_high']}] | {r['p_value']:.3f} |"
            for r in p1
        ),
        "",
        "Verdict: the pooling of the main analysis is "
        + ("supported (no row rejected)." if not any(rejected) else "not supported."),
        "",
    ]
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"S1 {agree}/{tested} agree; F1 flagged {flagged}; P1 {inside}/{len(p1)} inside, "
        f"{sum(rejected)} rejected"
    )


if __name__ == "__main__":
    main()
