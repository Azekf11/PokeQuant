"""Generate research/reports/valuation.md: price snapshot, coverage and card values (S6).

Publishes derived statistics only (ADR 0009): counts, shares and quantiles by
set and pool, never a per-card price. Reads the processed tables of the main
experiment (run `pokequant ingest ... --offline` first).

Usage: uv run python scripts/valuation_report.py
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from datetime import UTC
from pathlib import Path

import numpy as np

from pokequant_core.booster import LAYOUTS, build_pools
from pokequant_core.experiment import load_experiment
from pokequant_core.ingest.store import read_records
from pokequant_core.schemas import CardPrinting, PriceObservation
from pokequant_core.valuation import PriceBasis, sale_threshold, select_prices, value_cards

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "research/experiments/main.yaml"
REPORT = ROOT / "research/reports/valuation.md"


def drawable_pools(printings: Sequence[CardPrinting]) -> dict[str, list[str]]:
    """Pools of the printings a pack can contain under the main layout."""
    layout = LAYOUTS["tcgplayer"]
    names = {s.residual for s in layout.slots} | {r for s in layout.slots for r in s.hits}
    return {k: v for k, v in build_pools(printings).items() if k in names}


MIN_N = 5  # below this, quantiles would reveal individual prices: not published


def q(values: Sequence[float], p: float) -> str:
    return f"{np.quantile(values, p):.2f}" if len(values) >= MIN_N else "n/a"


def main() -> None:
    cfg = load_experiment(CONFIG)
    processed = ROOT / f"data/processed/pokelife-{cfg.data.pokelife}_tcgdex-{cfg.data.tcgdex}"
    manifest = json.loads((processed / "manifest.json").read_text())
    printings = read_records(processed / "printings.parquet", CardPrinting)
    observations = read_records(processed / "prices.parquet", PriceObservation)
    pricing = cfg.pricing
    basis = PriceBasis(
        pricing.venue,
        pricing.currency,
        pricing.price_type,
        pricing.statistic,
        pricing.condition,
        cfg.data.reference_date,
    )
    prices = select_prices(observations, basis)
    scenarios = {s.name: s for s in cfg.cost_scenarios}
    stamps = sorted(t.astimezone(UTC) for t in prices.observed_at.values())

    lines = [
        "# Valuation model v1 and price snapshot",
        "",
        "Generated by `scripts/valuation_report.py` from the processed tables of the main",
        f"experiment (`{processed.name}`, prices table sha256 "
        f"`{manifest['outputs']['prices']['sha256'][:12]}…`). Derived statistics only",
        "(ADR 0009): no per-card price is published.",
        "",
        "## 1. Price basis",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Venue, currency | {basis.venue}, {basis.currency} |",
        f"| Price type | `{basis.price_type}` (statistic `{basis.statistic}`) |",
        f"| Condition | {basis.condition} (not stated by the provider) |",
        f"| Reference date t0 | {basis.reference_date} |",
        f"| Observation times | {stamps[0]:%Y-%m-%d %H:%M} to {stamps[-1]:%Y-%m-%d %H:%M} UTC |",
        "| Relay | TCGdex API, fetched on the date of the snapshot |",
        "",
        "The price is a **provider market price**: an aggregate computed by TCGplayer",
        "with its own method. It is not an asking price (TCGplayer `low`, `mid`, `high`",
        "and `direct_low` are stored with type `listing` and never used as a",
        "transaction value) and it is not a realised sale observed by this study",
        "(type `sold`, for which no open source exists; S2 audit). The code refuses",
        "to value cards from a `listing` basis, to mix bases, to use observations",
        "made after t0 or more than 7 days before it, and to use graded prices.",
        "",
        "## 2. Coverage of the printings a pack can contain",
        "",
        "| Set | Pool | Printings | Priced | Missing |",
        "|---|---|---|---|---|",
    ]
    pools_by_set = {}
    missing_ids: list[str] = []
    for set_id in cfg.sets:
        pools = drawable_pools([p for p in printings if p.set_id == set_id])
        pools_by_set[set_id] = pools
        for name, ids in pools.items():
            miss = [p for p in ids if p not in prices.prices]
            missing_ids += miss
            lines.append(
                f"| {set_id} | {name} | {len(ids)} | {len(ids) - len(miss)} | {len(miss)} |"
            )
    lines += [
        "",
        f"Missing: {', '.join(f'`{m}`' for m in missing_ids) or 'none'}. In each case the",
        "TCGdex record has no TCGplayer block at all (a provider gap, not a filtering",
        "step). Missing prices are never read as 0: the central scenario imputes the",
        "median observed price of the printing's pool, the adverse scenario values",
        "the printing at 0 as a labelled prudent assumption (ADR 0010, item 8), and",
        "E2 targets and E1 baskets are chosen among observed prices only.",
        "",
        "## 3. Price distribution by pool (USD)",
        "",
        "| Set | Pool | n | Median | Q1 | Q3 | P90 | Share ≥ 1 USD |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for set_id, pools in pools_by_set.items():
        for name, ids in pools.items():
            v = [prices.prices[p] for p in ids if p in prices.prices]
            share = np.mean([x >= 1 for x in v]) if v else float("nan")
            lines.append(
                f"| {set_id} | {name} | {len(v)} | {q(v, 0.5)} | {q(v, 0.25)} | {q(v, 0.75)} "
                f"| {q(v, 0.9)} | {share:.0%} |"
            )
    lines += [
        "",
        f"Quantiles are not shown for pools with fewer than {MIN_N} priced printings.",
        "",
        "## 4. Liquidation and acquisition values by scenario",
        "",
        "A card is sold alone, so a fixed fee and shipping apply to each sale. Below",
        "the sale threshold, l(c) = 0: the card is kept or given away, never sold at",
        "a loss. The share of a pool's market value that a seller keeps is",
        "Σ l(c) / Σ p(c) over the pool, imputed prices included.",
        "",
        "| Scenario | Missing rule | Sale threshold (USD) |",
        "|---|---|---|",
    ]
    for name, s in scenarios.items():
        rule = pricing.missing_price.adverse if name == "adverse" else pricing.missing_price.central
        lines.append(f"| {name} | {rule} | {sale_threshold(s):.2f} |")
    lines += [
        "",
        "| Set | Pool | " + " | ".join(f"{n}: sold / kept" for n in scenarios) + " |",
        "|---|---|" + "---|" * len(scenarios),
    ]
    for set_id, pools in pools_by_set.items():
        values = {}
        for name, s in scenarios.items():
            rule = pricing.missing_price.adverse if name == "adverse" else (
                pricing.missing_price.central
            )  # fmt: skip
            values[name] = value_cards(prices, pools, s, rule)
        for pool, ids in pools.items():
            cells = []
            for cv in values.values():
                sold = np.mean([cv.liquidation[p] > 0 for p in ids])
                total = sum(cv.price[p] for p in ids)
                kept = sum(cv.liquidation[p] for p in ids) / total if total else float("nan")
                cells.append(f"{sold:.0%} / {kept:.0%}")
            lines.append(f"| {set_id} | {pool} | " + " | ".join(cells) + " |")
    lines += [
        "",
        '"Sold" is the share of the pool\'s printings with l(c) > 0; "kept" the share',
        "of the pool's market value received by the seller.",
        "",
        "## 5. Low-value bulk",
        "",
        "Commons, Uncommons and most reverse holos are priced below the sale",
        "threshold of the central and adverse scenarios, so they contribute 0 to l:",
        "the prudent treatment named in the roadmap. Selling them as a bulk lot",
        "would recover a little value, but no open, dated source of bulk-lot prices",
        "was found and this rule was not pre-registered; it is not used. The gross",
        "scenario values every card at its market price and is reported as a",
        "theoretical reference only.",
        "",
        "## 6. Why there is no hedonic regression",
        "",
        "The protocol (§5.2) allows a hedonic model only if the data have enough",
        "observations and variation. They do not, for the purpose of this study:",
        "",
        "- one cross-section per set at a single date, so no time variation within",
        "  a printing; age varies only between three sets, confounded with the set",
        "  effect δ_s;",
        "- no demand or liquidity proxy (sales volume, listings count) in an open",
        "  source; grade is absent (raw cards, condition unspecified);",
        "- the estimands use the observed price of each printing directly; a fitted",
        "  price would only replace observed values with predictions.",
        "",
        "Observed prices and labelled scenarios are therefore used, as the protocol",
        "recommends for the MVP.",
        "",
        "## 7. Dated snapshots",
        "",
        f"The main analysis uses the snapshot of {cfg.data.reference_date} only (static",
        f"design, protocol §6.1). A second snapshot is planned for {cfg.data.h4_snapshot_date}",
        "(hypothesis H4) with the same pipeline: `pokequant ingest` writes an immutable",
        "raw cache named by date and a processed directory whose manifest records the",
        "hash of every input and output.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
