"""Report of the Mega Evolution extension (ADR 0016, tag prereg-v5).

Reads the run of research/experiments/mega_sets.yaml (central layout, Mega
Hyper Rare in the second reverse slot), the paired run of
mega_sets_rare_slot.yaml (Mega Hyper Rare in the rare slot) and the ten-set run
of ADR 0015, and writes research/reports/mega_sets.md: C1-C3 and the
break-even price b* by set under both layouts (a check holds only if it holds
under both), H1-H4 over the four sets, and H4 over the fourteen sets.

Usage: uv run python scripts/mega_report.py results/<mega run> results/<rare-slot run>
       results/<ten-set run>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import numpy as np

from pokequant_core.analysis import hypotheses
from pokequant_core.experiment import load_experiment
from pokequant_core.experiment_run import processed_dir
from pokequant_core.ingest.store import read_records
from pokequant_core.metrics import epistemic_interval
from pokequant_core.robustness import check_conclusions
from pokequant_core.schemas import CardSet

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research/reports/mega_sets.md"
LAYOUTS = {"rev2": "MHR in second reverse slot (central)", "rare": "MHR in rare slot (M1)"}
CHECKS = ("C1", "C2", "C3")


def load(run_dir: Path) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    manifest = json.loads((run_dir / "manifest.json").read_text(encoding="utf-8"))
    results = json.loads((run_dir / "results.json").read_text(encoding="utf-8"))
    return manifest, results


def fmt(t: tuple[float, float, float]) -> str:
    return f"{t[0]:.2f} [{t[1]:.2f}, {t[2]:.2f}]"


def mark(flag: bool) -> str:
    return "yes" if flag else "**no**"


def summary(own: list[dict[str, Any]], cost: float) -> dict[str, Any]:
    e1 = next(r for r in own if r["job"]["label"] == "n=36")
    b: dict[str, tuple[float, float, float]] = {}
    for scenario in ("central", "gross"):
        x = np.asarray(e1["extra"]["break_even_booster_price"][scenario])
        b[scenario] = (float(x.mean()), *epistemic_interval(x))
    mean36 = np.asarray(e1["a_metrics"]["central"]["mean"])
    return {
        "b": b,
        "mean36": (float(mean36.mean()), *epistemic_interval(mean36)),
        "b36": float(e1["b_metrics"]["central"]["mean"]),
        "checks": check_conclusions(own, cost),
    }


def main(central_dir: Path, rare_dir: Path, ten_dir: Path) -> None:
    manifest, central = load(central_dir)
    rare_manifest, rare = load(rare_dir)
    _, ten = load(ten_dir)
    cfg = load_experiment(ROOT / manifest["run"]["parameters"]["config"])
    cost = cfg.scenario("central").booster_cost
    names = {
        s.set_id: s.name for s in read_records(processed_dir(ROOT, cfg) / "sets.parquet", CardSet)
    }
    rows: list[dict[str, Any]] = []
    for set_id in cfg.sets:
        by_layout = {
            "rev2": summary([r for r in central if r["set_id"] == set_id], cost),
            "rare": summary([r for r in rare if r["set_id"] == set_id], cost),
        }
        holds = {c: all(by_layout[k]["checks"][c]["holds"] for k in LAYOUTS) for c in CHECKS}
        rows.append({"set_id": set_id, "name": names[set_id], **by_layout, "holds": holds})

    lines = [
        "# Mega Evolution sets (ADR 0016, tag `prereg-v5`)",
        "",
        "Generated by `scripts/mega_report.py` from runs",
        f"`{central_dir.name}` (results SHA-256 `{manifest['results_sha256'][:16]}…`) and",
        f"`{rare_dir.name}` (results SHA-256 `{rare_manifest['results_sha256'][:16]}…`).",
        "Same seed, prior, draws, runs, scenarios and price snapshot as the main run;",
        "TCGplayer market prices in USD of 2026-11-15, condition unspecified. The slot of",
        "the Mega Hyper Rare (MHR) is not documented: the central layout puts it in the",
        "second reverse slot, the paired alternative M1 in the rare slot.",
        "",
        "## Break-even booster price b* (posterior mean [95 % interval], USD)",
        "",
        "| Set | Central costs, MHR in reverse slot | Central costs, MHR in rare slot "
        "| Gross, MHR in reverse slot | Gross, MHR in rare slot |",
        "|---|---|---|---|---|",
        *(
            f"| {r['name']} ({r['set_id']}) | {fmt(r['rev2']['b']['central'])} "
            f"| {fmt(r['rare']['b']['central'])} | {fmt(r['rev2']['b']['gross'])} "
            f"| {fmt(r['rare']['b']['gross'])} |"
            for r in rows
        ),
        "",
        "## Thirty-six boosters, central costs, central layout (USD)",
        "",
        "| Set | A: mean profit of opening | B: profit of buying |",
        "|---|---|---|",
        *(
            f"| {r['name']} ({r['set_id']}) | {fmt(r['rev2']['mean36'])} | {r['rev2']['b36']:.2f} |"
            for r in rows
        ),
        "",
        "## Conclusions by set (a check holds only if it holds under both layouts)",
        "",
        "| Set | C1 (rev / rare) | C2 (rev / rare) | C3 (rev / rare) | Holds under both |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        cells = [
            f"{mark(r['rev2']['checks'][c]['holds'])} / {mark(r['rare']['checks'][c]['holds'])}"
            for c in CHECKS
        ]
        both = ", ".join(c for c in CHECKS if r["holds"][c]) or "none"
        lines.append(f"| {r['name']} ({r['set_id']}) | " + " | ".join(cells) + f" | {both} |")
    fails = [
        f"- {r['set_id']} {c} ({layout}): " + "; ".join(r[layout]["checks"][c]["fails"])
        for r in rows
        for layout in LAYOUTS
        for c in CHECKS
        if not r[layout]["checks"][c]["holds"]
    ]
    lines += ["", "Failures:" if fails else "Failures: none.", *fails, ""]

    h_rev, h_rare = hypotheses(central), hypotheses(rare)
    h_all = hypotheses([*ten, *central])
    lines += [
        "## Hypotheses",
        "",
        "| Hypothesis | Four sets, MHR in reverse slot | Four sets, MHR in rare slot "
        "| Fourteen sets (ten-set run + central layout) |",
        "|---|---|---|---|",
        *(
            f"| {h} | {h_rev[h]['status']} | {h_rare[h]['status']} "
            f"| {h_all[h]['status'] if h == 'H4' else 'n/a'} |"
            for h in ("H1", "H2", "H3", "H4")
        ),
        "",
        "### H4 evidence over the fourteen sets (decisive winner on the mean, central)",
        "",
        *(f"- {line}" for line in h_all["H4"]["evidence"]),
        "",
        "### H1 and H2 evidence (four sets, central layout)",
        "",
        *(f"- H1: {line}" for line in h_rev["H1"]["evidence"]),
        *(f"- H2: {line}" for line in h_rev["H2"]["evidence"]),
        "",
        "H4 here covers sets only. The date half of H4 uses the weekly panel of ADR 0014.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]))
